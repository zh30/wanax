use std::path::Path;
use std::process::Command;
use wanax_core::config::ResolvedConfig;
use wanax_core::error::{ErrorCode, WanaxError};

/// Create a GitHub PR after accept when configured. Runs in the outer process only.
pub fn maybe_create_github_pr(
    repo: &Path,
    inner_branch: &str,
    run_id: &str,
    cfg: &ResolvedConfig,
) -> Result<Option<String>, WanaxError> {
    let enabled =
        cfg.file.github.create_pr || std::env::var("WANAX_CREATE_PR").ok().as_deref() == Some("1");
    if !enabled {
        return Ok(None);
    }
    let has_token = std::env::var("GH_TOKEN")
        .ok()
        .filter(|s| !s.is_empty())
        .is_some()
        || std::env::var("GITHUB_TOKEN")
            .ok()
            .filter(|s| !s.is_empty())
            .is_some();
    if !has_token {
        tracing::warn!("github.create_pr enabled but GH_TOKEN missing in outer process");
        return Ok(None);
    }
    let title = format!("wanax: {run_id}");
    let body = pr_body(repo, run_id, inner_branch);
    let out = Command::new("gh")
        .args([
            "pr",
            "create",
            "--head",
            inner_branch,
            "--title",
            &title,
            "--body",
            &body,
        ])
        .current_dir(repo)
        .output()
        .map_err(|e| WanaxError::with_detail(ErrorCode::Db, e))?;
    if !out.status.success() {
        let stderr = String::from_utf8_lossy(&out.stderr);
        return Err(WanaxError::new(
            ErrorCode::Db,
            format!("gh pr create failed: {}", stderr.trim()),
        ));
    }
    let url = String::from_utf8_lossy(&out.stdout).trim().to_string();
    Ok(Some(url))
}

/// Evidence summary for the PR body — verdict chain, mechanical gates,
/// spend, and diffstat, mined straight from the tombstone envelope so
/// the reviewer sees the run's own record rather than a claim about it.
fn pr_body(repo: &Path, run_id: &str, inner_branch: &str) -> String {
    let mut b = format!(
        "Automated factory run `{run_id}` — branch `{inner_branch}`.\n\n**Human review + merge required.** Wanax never merges protected refs.\n"
    );
    if let Ok(env) = wanax_tombstone::load_envelope(repo, run_id) {
        let verdicts: Vec<String> = env
            .events
            .iter()
            .filter(|e| e.kind.as_str() == "verdict")
            .filter_map(|e| e.payload["decision"].as_str().map(String::from))
            .collect();
        if !verdicts.is_empty() {
            b.push_str(&format!("\n- verdicts: {}\n", verdicts.join(" → ")));
        }
        let mut gates = Vec::new();
        for e in &env.events {
            match e.kind.as_str() {
                "outer_test_finished" => gates.push(format!(
                    "outer_test exit {}",
                    e.payload["exit_code"].as_i64().unwrap_or(-1)
                )),
                "baseline_test" => gates.push(format!(
                    "baseline exit {}",
                    e.payload["exit_code"].as_i64().unwrap_or(-1)
                )),
                "bound_test" => gates.push(format!(
                    "bound `{}` {}",
                    e.payload["name"].as_str().unwrap_or("?"),
                    if e.payload["ok"].as_bool().unwrap_or(false) {
                        "ok"
                    } else {
                        "FAILED"
                    }
                )),
                "must_have" => gates.push("must_have passed".to_string()),
                "boundary_violation" => gates.push(format!(
                    "boundary violations: {}",
                    e.payload["paths"].as_array().map(|a| a.len()).unwrap_or(0)
                )),
                _ => {}
            }
        }
        if !gates.is_empty() {
            b.push_str(&format!("- gates: {}\n", gates.join(" · ")));
        }
        if let Some(spent) = env
            .events
            .iter()
            .rev()
            .find_map(|e| e.payload["spent_usd_micros"].as_i64())
        {
            b.push_str(&format!(
                "- spent: {}\n",
                wanax_core::money::format_usd_4(spent)
            ));
        }
        b.push_str(&format!("- envelope: {} events\n", env.events.len()));
    }
    if let Ok(diff) = wanax_git::diff_stat(repo, "HEAD", inner_branch) {
        if !diff.trim().is_empty() {
            b.push_str(&format!("\n```\n{diff}```\n"));
        }
    }
    b.push_str("\n_Generated by wanax_\n");
    b
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pr_body_summarizes_gates_and_verdicts() {
        let dir = tempfile::tempdir().unwrap();
        let repo = dir.path();
        let run_dir = repo.join(".wanax").join("runs").join("wx_test1");
        std::fs::create_dir_all(&run_dir).unwrap();
        let env_json = serde_json::json!({
            "schema_version": "3",
            "run_id": "wx_test1",
            "contract_sha256": "abc",
            "current_state": "accepted",
            "events": [
                {"id":"e1","at":"t","actor":"system","kind":"run_started","payload":{},"payload_sha256":"x"},
                {"id":"e2","at":"t","actor":"verifier","kind":"outer_test_finished","payload":{"exit_code":0},"payload_sha256":"x"},
                {"id":"e3","at":"t","actor":"verifier","kind":"bound_test","payload":{"name":"mul_works","ok":true},"payload_sha256":"x"},
                {"id":"e4","at":"t","actor":"commander","kind":"verdict","payload":{"decision":"accept"},"payload_sha256":"x"},
                {"id":"e5","at":"t","actor":"system","kind":"budget_tick","payload":{"spent_usd_micros":65000},"payload_sha256":"x"},
            ]
        });
        std::fs::write(
            run_dir.join("envelope.json"),
            serde_json::to_string(&env_json).unwrap(),
        )
        .unwrap();
        let body = pr_body(repo, "wx_test1", "wanax/wx_test1/inner");
        assert!(body.contains("verdicts: accept"), "{body}");
        assert!(body.contains("bound `mul_works` ok"), "{body}");
        assert!(body.contains("outer_test exit 0"), "{body}");
        assert!(body.contains("0.0650"), "{body}");
        assert!(body.contains("Human review"), "{body}");
    }
}
